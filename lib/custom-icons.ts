export type MaterializedCustomIcon = SimpleIcon & {
  paths: CustomIconPath[];
  viewBox?: CustomIconViewBox;
};

export function materializeCustomIcon(
  icon: CustomIcon,
): MaterializedCustomIcon {
  const paths = icon.paths ??
    (icon.path && icon.hex ? [{ path: icon.path, hex: icon.hex }] : []);

  if (paths.length === 0) {
    throw new Error(`custom icon ${icon.slug} must define path/hex or paths`);
  }

  const firstPath = paths[0];
  if (!firstPath) {
    throw new Error(`custom icon ${icon.slug} has no drawable paths`);
  }

  const viewBox = icon.viewBox ?? { width: 24, height: 24 };

  return {
    ...icon,
    path: paths.map((item) => item.path).join(" "),
    hex: firstPath.hex,
    paths,
    svg: `<svg viewBox="0 0 ${viewBox.width} ${viewBox.height}">${paths.map((item) => `<path fill="#${item.hex}" d="${item.path}"/>`).join("")}</svg>`,
  };
}
